def _load_used_topics() -> List[str]:
    try:
        if USED_TOPICS_FILE.exists():
            data = json.loads(USED_TOPICS_FILE.read_text(encoding="utf-8"))
            return data if isinstance(data, list) else []
    except (OSError, json.JSONDecodeError):
        pass
    return []


def _remember_topic(topic: str) -> None:
    used = _load_used_topics()
    if topic not in used:
        used.append(topic)
    # Keep the file small enough to avoid unnecessary growth.
    used = used[-500:]
    try:
        USED_TOPICS_FILE.parent.mkdir(parents=True, exist_ok=True)
        tmp = USED_TOPICS_FILE.with_suffix(".tmp")
        tmp.write_text(json.dumps(used, ensure_ascii=False, indent=2), encoding="utf-8")
        tmp.replace(USED_TOPICS_FILE)
    except OSError as exc:
        print(f"⚠️ Could not update topic history: {exc}")


def _normalize_script(data: Dict[str, Any]) -> Dict[str, Any]:
    """Validate a script and split multi-sentence scenes into matching visual beats."""
    topic = str(data.get("topic") or data.get("title") or "Daily Urdu knowledge").strip()
    title = str(data.get("title") or topic).strip()[:140]
    badge = str(data.get("category_badge") or data.get("category") or "FUN KNOWLEDGE").strip()[:28]
    hashtags = str(data.get("hashtags") or "#UrduFacts #PakistaniReels #FunnyKnowledge").strip()
    raw_scenes = data.get("scenes")
    if not isinstance(raw_scenes, list):
        raise ValueError("Script response has no scenes array")

    scenes: List[Dict[str, Any]] = []
    for raw in raw_scenes[:10]:
        if not isinstance(raw, dict):
            continue
        narration = str(raw.get("tts_urdu") or raw.get("narration") or raw.get("voiceover") or "").strip()
        if len(narration) < 12:
            continue

        queries = raw.get("visual_queries") or raw.get("visuals") or []
        if isinstance(queries, str):
            queries = [queries]
        if not isinstance(queries, list):
            queries = []
        queries = [str(q).strip() for q in queries if str(q).strip()][:3]
        if not queries:
            queries = [f"realistic documentary photo about {topic}"]

        sentences = split_narration_sentences(narration)
        if not sentences:
            continue
        raw_sfx = str(raw.get("sound_effect") or raw.get("sfx") or "none").lower().strip()
        if raw_sfx not in ALLOWED_SFX:
            raw_sfx = "none"
        raw_sfx_at = str(raw.get("sfx_at") or "middle").lower().strip()
        if raw_sfx_at not in {"start", "middle", "end"}:
            raw_sfx_at = "middle"
        sfx_target = 0 if raw_sfx_at == "start" else (len(sentences) - 1 if raw_sfx_at == "end" else len(sentences) // 2)

        for sentence_index, sentence in enumerate(sentences):
            if len(scenes) >= 12:
                break
            # For multi-sentence source scenes, use the matching visual query by sentence.
            primary_query = queries[min(sentence_index, len(queries) - 1)]
            if len(queries) == 1:
                secondary_query = f"{primary_query} close-up detail"
            else:
                secondary_query = f"{primary_query} close-up detail"
            # Keep the video query tied to this sentence, never to the whole video topic.
            raw_video_query = str(raw.get("video_query") or "").strip()
            video_query = raw_video_query if sentence_index == 0 and raw_video_query else primary_query
            sentence_sfx = raw_sfx if sentence_index == sfx_target else "none"
            scenes.append({
                "tts_urdu": normalize_narration_text(sentence),
                "visual_queries": [primary_query, secondary_query],
                "video_query": video_query,
                "sound_effect": sentence_sfx,
                "sfx_at": raw_sfx_at if sentence_sfx != "none" else "start",
            })
        if len(scenes) >= 12:
            break

    if len(scenes) < 4:
        raise ValueError("Script has fewer than four usable spoken visual beats")
    return {
        "topic": topic,
        "title": title,
        "hashtags": hashtags,
        "category_badge": badge,
        "scenes": scenes,
    }


