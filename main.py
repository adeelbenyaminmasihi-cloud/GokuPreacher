def synthesize_scene_voice(text: str, index: int, workdir: Path) -> Tuple[Path, Path]:
    raw_audio = workdir / f"voice_raw_{index:02d}.mp3"
    metadata = workdir / f"voice_words_{index:02d}.jsonl"
    try:
        asyncio.run(_synthesize_scene_voice_async(text, raw_audio, metadata))
    except RuntimeError as exc:
        # asyncio.run can fail if an event loop is already active (e.g. notebooks).
        if "asyncio.run() cannot be called" not in str(exc):
            raise
        loop = asyncio.new_event_loop()
        try:
            loop.run_until_complete(_synthesize_scene_voice_async(text, raw_audio, metadata))
        finally:
            loop.close()
    if not raw_audio.exists() or raw_audio.stat().st_size < 3000:
        raise RuntimeError(f"Edge TTS did not create audio for scene {index + 1}.")
    return raw_audio, metadata


def read_word_boundaries(metadata_path: Path, narration: str, duration: float) -> List[Dict[str, Any]]:
    words: List[Dict[str, Any]] = []
    try:
        with metadata_path.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    item = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if item.get("type") not in {"WordBoundary", "SentenceBoundary"}:
                    continue
                word = str(item.get("text") or "").strip()
                if not word:
                    continue
                # Edge TTS timestamps are expressed in 100-nanosecond ticks.
                start = float(item.get("offset", 0)) / 10_000_000.0
                word_duration = float(item.get("duration", 0)) / 10_000_000.0
                words.append({"text": word, "start": max(0.0, start), "end": max(0.0, start + word_duration)})
    except OSError:
        pass

    words.sort(key=lambda item: item["start"])
    if words:
        # Remove duplicate/overlapping boundary tokens from odd service responses.
        cleaned: List[Dict[str, Any]] = []
        last_start = -1.0
        for item in words:
            if item["start"] + 0.005 < last_start:
                continue
            if item["start"] > duration + 0.5:
                continue
            cleaned.append(item)
            last_start = item["start"]
        if cleaned:
            return cleaned

    # Fallback: estimate timings from narration length if the TTS service omits metadata.
    tokens = re.findall(r"\S+", narration)
    weights = [max(1.0, len(token.strip("،۔!?؛:,.!?"))) ** 0.72 for token in tokens]
    total = sum(weights) or 1.0
    cursor = max(0.0, duration * 0.035)
    available = max(0.1, duration - cursor - 0.03)
    for token, weight in zip(tokens, weights):
        segment = available * weight / total
        words.append({"text": token, "start": cursor, "end": cursor + segment})
        cursor += segment
    return words


def _caption_groups(words: List[Dict[str, Any]], duration: float) -> List[Dict[str, Any]]:
    """Group actual TTS word boundaries into readable subtitle cues."""
    if not words:
        return [{"text": "", "start": 0.0, "end": duration}]

    groups: List[Dict[str, Any]] = []
    current: List[Dict[str, Any]] = []
    current_chars = 0
    max_words = 5
    max_chars = 29
    punctuation = re.compile(r"[.!?؟۔،;؛:]$")

    def flush() -> None:
        nonlocal current, current_chars
        if not current:
            return
        text = " ".join(word["text"] for word in current).strip()
        groups.append({
            "text": text,
            "start": float(current[0]["start"]),
            "last_end": float(current[-1]["end"]),
        })
        current = []
        current_chars = 0

    for word in words:
        word_text = str(word["text"]).strip()
        if not word_text:
            continue
        next_chars = current_chars + len(word_text) + (1 if current else 0)
        if current and (len(current) >= max_words or next_chars > max_chars):
            flush()
        current.append(word)
        current_chars += len(word_text) + 1
        if punctuation.search(word_text):
            flush()
    flush()

    # Apply small lead-in/lead-out padding without letting adjacent captions overlap.
    for i, cue in enumerate(groups):
        raw_start = float(cue["start"])
        start = min(max(0.0, raw_start - 0.025), max(0.0, duration - 0.05))
        last_end = float(cue.get("last_end", raw_start + 0.15))
        if i + 1 < len(groups):
            next_start = max(0.0, float(groups[i + 1]["start"]) - 0.025)
            latest_end = max(start + 0.08, next_start - 0.015)
            end = min(max(last_end + 0.12, start + 0.12), latest_end)
        else:
            end = min(duration, max(last_end + 0.18, start + 0.15))
        cue["start"] = start
        cue["end"] = max(start + 0.06, min(duration, end))
    return groups


def _ass_timestamp(seconds: float) -> str:
    centiseconds = max(0, int(round(seconds * 100)))
    hours, centiseconds = divmod(centiseconds, 360000)
    minutes, centiseconds = divmod(centiseconds, 6000)
    seconds_part, centiseconds = divmod(centiseconds, 100)
    return f"{hours}:{minutes:02d}:{seconds_part:02d}.{centiseconds:02d}"


def _escape_ass_text(text: str) -> str:
    # Preserve Urdu and punctuation while protecting ASS special characters.
    return text.replace("\\", r"\\").replace("{", r"\{").replace("}", r"\}").replace("\n", r"\N")


