def infer_sfx(narration: str) -> str:
    text = narration.lower()
    if any(word in text for word in ("پیسے", "روپے", "رقم", "خرید", "پارسل", "بل", "خرچہ", "اکاؤنٹ")):
        return "cash"
    if any(word in text for word in ("فون", "موبائل", "کال", "میسج", "او ٹی پی", "پاس ورڈ")):
        return "alert"
    if any(word in text for word in ("گاڑی", "انجن", "بائیک", "موٹر", "ٹائر")):
        return "engine"
    if any(word in text for word in ("گرمی", "چارج", "سولر", "بجلی", "روشنی")):
        return "zap"
    if any(word in text for word in ("غلط", "افواہ", "چور", "فراڈ", "اسکیم", "اسکیم")):
        return "scratch"
    return random.choice(["whoosh", "pop", "ding", "boing"])


def _sfx_delay(scene: Dict[str, Any], duration: float) -> float:
    point = str(scene.get("sfx_at", "middle")).lower()
    if point == "start":
        return min(0.18, duration * 0.05)
    if point == "end":
        return max(0.0, duration - 0.9)
    return max(0.15, min(duration * 0.52, duration - 0.65))


def mix_scene_voice_and_sfx(
    voice_path: Path,
    sfx_type: str,
    delay_sec: float,
    out_audio: Path,
    workdir: Path,
    scene_index: int,
) -> Path:
    effect = _make_sfx(sfx_type, workdir / f"sfx_{scene_index:02d}.wav")
    if effect is None:
        shutil.copy2(voice_path, out_audio)
        return out_audio
    delay_ms = max(0, int(delay_sec * 1000))
    try:
        run_ffmpeg([
            "-i", str(voice_path), "-i", str(effect),
            "-filter_complex",
            f"[1:a]volume=0.22,adelay={delay_ms}|{delay_ms}[fx];"
            "[0:a][fx]amix=inputs=2:duration=first:dropout_transition=0:normalize=0,"
            "alimiter=limit=0.95[a]",
            "-map", "[a]", "-ar", "44100", "-ac", "2",
            "-c:a", "aac", "-b:a", "160k", str(out_audio),
        ])
        return out_audio
    except Exception as exc:
        print(f"   ⚠️ Sound effect mix failed for scene {scene_index + 1}: {exc}; keeping clean voiceover.")
        shutil.copy2(voice_path, out_audio)
        return out_audio


def render_scene(scene: Dict[str, Any], index: int, total_scenes: int, script_data: Dict[str, Any], workdir: Path) -> Path:
    narration = normalize_narration_text(scene["tts_urdu"])
    scene["tts_urdu"] = narration
    print(f"🎬 Beat {index + 1}/{total_scenes}: {narration[:64]}{'…' if len(narration) > 64 else ''}")
    raw_voice, metadata = synthesize_scene_voice(narration, index, workdir)

    # Light mastering without silence removal, so Edge TTS word timestamps stay aligned.
    mastered_voice = workdir / f"voice_master_{index:02d}.m4a"
    run_ffmpeg([
        "-i", str(raw_voice),
        "-af", "highpass=f=65,acompressor=threshold=-18dB:ratio=2.4:attack=8:release=90:makeup=2dB,loudnorm=I=-16:TP=-1.5:LRA=11",
        "-ar", "44100", "-ac", "2", "-c:a", "aac", "-b:a", "160k", str(mastered_voice),
    ])
    duration = get_audio_duration(mastered_voice)
    sub_path = workdir / f"subtitles_{index:02d}.ass"
    create_timed_subtitles(metadata, narration, duration, sub_path)

    queries = scene.get("visual_queries") or [f"realistic documentary visual about {script_data['topic']}"]
    if len(queries) < 2:
        queries = list(queries) + [str(queries[0]) + " close-up detail"]
    primary_query = str(queries[0]).strip()
    secondary_query = str(queries[1]).strip()
    query_video = str(scene.get("video_query") or primary_query).strip()
    video_path = fetch_contextual_stock_video(query_video, workdir / f"stock_{index:02d}.mp4")
    if not video_path and primary_query.lower() != query_video.lower():
        # Retry with the exact photo query if Gemini's separate video query is too narrow.
        video_path = fetch_contextual_stock_video(primary_query, workdir / f"stock_{index:02d}.mp4")
    if video_path:
        first_media, first_is_video = video_path, True
        scene["_primary_visual_source"] = "Pexels stock video"
    else:
        first_media = fetch_exact_scene_photo(primary_query, workdir / f"photo_{index:02d}_a.jpg")
        first_is_video = False
        scene["_primary_visual_source"] = "scene-matched photo / generated visual"

    # Each narration beat has one principal visual. Only add a second closely related
    # close-up for longer lines, preventing rapid unrelated cuts during short sentences.
    total_frames = max(6, int(math.ceil(duration * FPS)))
    cut_specs = [(first_media, first_is_video, total_frames / FPS, "a")]
    if duration >= 4.4:
        second_media = fetch_exact_scene_photo(secondary_query, workdir / f"photo_{index:02d}_b.jpg")
        first_frames = max(1, int(round(total_frames * 0.62)))
        second_frames = max(1, total_frames - first_frames)
        if first_frames + second_frames > total_frames:
            second_frames = total_frames - first_frames
        cut_specs = [
            (first_media, first_is_video, first_frames / FPS, "a"),
            (second_media, False, second_frames / FPS, "b"),
        ]
    scene["_visual_queries_used"] = [primary_query] + ([secondary_query] if len(cut_specs) > 1 else [])
    print(f"   🎞️ Primary visual: {primary_query}")
    clip_paths: List[Path] = []
    for media, is_video, cut_duration, suffix in cut_specs:
        brand_overlay = create_brand_overlay(
            script_data.get("category_badge", "FUN KNOWLEDGE"), index, total_scenes,
            workdir / f"brand_{index:02d}_{suffix}.png",
        )
        clip = workdir / f"visual_{index:02d}_{suffix}.mp4"
        prepare_visual_subclip(media, is_video, brand_overlay, cut_duration, clip)
        clip_paths.append(clip)

    visual_list = workdir / f"visual_list_{index:02d}.txt"
    with visual_list.open("w", encoding="utf-8") as handle:
        for clip in clip_paths:
            # Paths are generated in our controlled temp directory; normalize quote chars.
            handle.write(f"file '{clip.as_posix().replace(chr(39), chr(39) + chr(92) + chr(39) + chr(39))}'\n")
    visual_concat = workdir / f"visual_concat_{index:02d}.mp4"
    run_ffmpeg([
        "-f", "concat", "-safe", "0", "-i", str(visual_list),
        "-an", "-c:v", "libx264", "-preset", "veryfast", "-crf", "21",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(visual_concat),
    ])

    requested_sfx = str(scene.get("sound_effect") or "").lower()
    if requested_sfx not in ALLOWED_SFX:
        requested_sfx = infer_sfx(narration)
    if requested_sfx == "none":
        mixed_voice = mastered_voice
    else:
        mixed_voice = mix_scene_voice_and_sfx(
            mastered_voice, requested_sfx, _sfx_delay(scene, duration),
            workdir / f"voice_sfx_{index:02d}.m4a", workdir, index,
        )

    scene_out = workdir / f"scene_final_{index:02d}.mp4"
    subtitle_filter = f"subtitles=filename='{ffmpeg_filter_path(sub_path)}'"
    run_ffmpeg([
        "-i", str(visual_concat), "-i", str(mixed_voice),
        "-vf", subtitle_filter,
        "-map", "0:v:0", "-map", "1:a:0",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "20",
        "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "192k",
        "-shortest", "-movflags", "+faststart", str(scene_out),
    ])
    if not _validate_video(scene_out):
        raise RuntimeError(f"Rendered scene {index + 1} is not a valid video.")
    return scene_out

