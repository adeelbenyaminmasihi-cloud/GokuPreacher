def _download_file(url: str, filename: Path, timeout: int = 18) -> bool:
    try:
        response = requests.get(url, headers=HEADERS, timeout=timeout, stream=True)
        if response.status_code != 200:
            return False
        content_type = response.headers.get("content-type", "").lower()
        if content_type and not ("image" in content_type or "video" in content_type or "octet-stream" in content_type):
            return False
        filename.parent.mkdir(parents=True, exist_ok=True)
        written = 0
        with filename.open("wb") as handle:
            for chunk in response.iter_content(chunk_size=256 * 1024):
                if not chunk:
                    continue
                written += len(chunk)
                # Protect against accidentally downloading multi-hundred-megabyte originals.
                if written > 120 * 1024 * 1024:
                    return False
                handle.write(chunk)
        return filename.exists() and filename.stat().st_size > 8000
    except requests.RequestException:
        return False
    finally:
        try:
            response.close()  # type: ignore[possibly-undefined]
        except Exception:
            pass


def _pexels_image(query: str, filename: Path) -> Optional[Path]:
    """Search Pexels in relevance order; never randomly shuffle scene candidates."""
    if not PEXELS_API_KEY:
        return None
    try:
        response = requests.get(
            "https://api.pexels.com/v1/search",
            headers={"Authorization": PEXELS_API_KEY},
            params={"query": query, "per_page": 12, "orientation": "portrait"},
            timeout=14,
        )
        response.raise_for_status()
        photos = response.json().get("photos", [])
        ranked = sorted(
            enumerate(photos),
            key=lambda pair: (-_query_relevance_score(query, str(pair[1].get("alt") or "")), pair[0]),
        )
        for _, photo in ranked:
            src = photo.get("src", {})
            url = src.get("large2x") or src.get("large") or src.get("original")
            if not url or url in USED_MEDIA_URLS:
                continue
            if _download_file(url, filename, timeout=18) and verify_and_grade_image(filename):
                USED_MEDIA_URLS.add(url)
                print(f"   🖼️ Photo matched: {query}")
                return filename
    except Exception as exc:
        print(f"   Pexels photo search skipped for '{query}': {exc}")
    return None


def _pexels_video(query: str, filename: Path) -> Optional[Path]:
    if not PEXELS_API_KEY:
        return None
    try:
        response = requests.get(
            "https://api.pexels.com/v1/videos/search",
            headers={"Authorization": PEXELS_API_KEY},
            params={"query": query, "per_page": 8, "orientation": "portrait"},
            timeout=12,
        )
        response.raise_for_status()
        videos = response.json().get("videos", [])
        candidates: List[Tuple[int, int, int, str]] = []
        for video_rank, video in enumerate(videos):
            for item in video.get("video_files", []):
                link = item.get("link")
                width, height = int(item.get("width") or 0), int(item.get("height") or 0)
                if not link or link in USED_MEDIA_URLS or item.get("file_type") not in ("video/mp4", None):
                    continue
                portrait_penalty = 0 if height >= width else 10000
                resolution_score = abs(min(width, 1080) - 1080) + abs(min(height, 1920) - 1920)
                # Keep Pexels' search relevance as the first sort key, then choose
                # the best available orientation/resolution within that result.
                candidates.append((video_rank, portrait_penalty + resolution_score, -(width * height), link))
        for _, _, _, url in sorted(candidates, key=lambda x: (x[0], x[1], x[2])):
            if _download_file(url, filename, timeout=30):
                USED_MEDIA_URLS.add(url)
                print(f"   🎥 Video matched: {query}")
                return filename
    except Exception as exc:
        print(f"   Pexels video search skipped: {exc}")
    return None


