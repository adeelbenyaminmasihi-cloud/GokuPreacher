def run_ffmpeg(args: Sequence[str], *, quiet: bool = True) -> None:
    """Run FFmpeg and raise a helpful error if rendering fails."""
    cmd = ["ffmpeg", "-hide_banner", "-y", *map(str, args)]
    try:
        subprocess.run(
            cmd,
            check=True,
            stdout=subprocess.DEVNULL if quiet else None,
            stderr=subprocess.DEVNULL if quiet else None,
        )
    except FileNotFoundError as exc:
        raise RuntimeError("FFmpeg was not found. Install FFmpeg and add it to PATH.") from exc
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(
            "FFmpeg could not render a media file. Check that FFmpeg includes the 'subtitles' / libass filter."
        ) from exc


def get_audio_duration(audio_path: Path) -> float:
    try:
        out = subprocess.check_output([
            "ffprobe", "-v", "error", "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1", str(audio_path),
        ], stderr=subprocess.DEVNULL).decode("utf-8", errors="replace").strip()
        return max(float(out), 0.3)
    except Exception as exc:
        raise RuntimeError(f"Could not read audio duration for {audio_path}: {exc}") from exc


def ffmpeg_filter_path(path: Path) -> str:
    # FFmpeg filter option paths require ':' escaping on Windows.
    value = path.resolve().as_posix().replace(":", r"\:").replace("'", r"\'")
    return value


