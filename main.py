def create_brand_overlay(badge_text: str, scene_index: int, total_scenes: int, out_png: Path) -> Path:
    overlay = Image.new("RGBA", (VIDEO_WIDTH, VIDEO_HEIGHT), (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    # Subtle top shade + lower caption contrast gradient.
    for y in range(0, 300):
        alpha = int(130 * (1 - y / 300))
        draw.line((0, y, VIDEO_WIDTH, y), fill=(3, 5, 10, alpha))
    for y in range(1180, VIDEO_HEIGHT):
        alpha = min(175, int(175 * (y - 1180) / (VIDEO_HEIGHT - 1180)))
        draw.line((0, y, VIDEO_WIDTH, y), fill=(3, 5, 10, alpha))

    badge_font = load_font(31)
    small_font = load_font(24)
    label = re.sub(r"\s+", " ", badge_text.upper()).strip()[:28] or "FUN KNOWLEDGE"
    box_w, box_h = min(780, max(300, len(label) * 23 + 85)), 74
    box_x, box_y = (VIDEO_WIDTH - box_w) // 2, 72
    draw.rounded_rectangle(
        (box_x, box_y, box_x + box_w, box_y + box_h),
        radius=36, fill=(11, 17, 29, 225), outline=(255, 207, 68, 245), width=3,
    )
    bbox = draw.textbbox((0, 0), label, font=badge_font)
    text_w = bbox[2] - bbox[0]
    draw.text((VIDEO_WIDTH // 2 - text_w // 2, box_y + 18), label, font=badge_font, fill=(255, 224, 104, 255))

    marker = f"{scene_index + 1:02d} / {total_scenes:02d}"
    draw.text((VIDEO_WIDTH - 155, 174), marker, font=small_font, fill=(255, 255, 255, 205))
    bar_x1, bar_y, bar_x2 = 70, 1810, VIDEO_WIDTH - 70
    draw.rounded_rectangle((bar_x1, bar_y, bar_x2, bar_y + 9), radius=5, fill=(255, 255, 255, 70))
    progress = (scene_index + 1) / max(1, total_scenes)
    draw.rounded_rectangle((bar_x1, bar_y, bar_x1 + int((bar_x2 - bar_x1) * progress), bar_y + 9), radius=5, fill=(255, 207, 68, 235))
    out_png.parent.mkdir(parents=True, exist_ok=True)
    overlay.save(out_png)
    return out_png


def _validate_video(path: Path) -> bool:
    try:
        result = subprocess.run(
            ["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "json", str(path)],
            check=True, capture_output=True, text=True,
        )
        streams = json.loads(result.stdout).get("streams", [])
        return bool(streams and int(streams[0].get("width", 0)) >= 200 and int(streams[0].get("height", 0)) >= 200)
    except Exception:
        return False


def prepare_visual_subclip(
    media_path: Path,
    is_video: bool,
    overlay_path: Path,
    duration: float,
    out_clip: Path,
) -> None:
    """Fill a 9:16 frame, add tasteful contrast/brand graphics, and export silent video."""
    duration = max(0.20, duration)
    if is_video:
        input_args = ["-stream_loop", "-1", "-t", f"{duration:.4f}", "-i", str(media_path)]
        source_filter = (
            f"scale={VIDEO_WIDTH}:{VIDEO_HEIGHT}:force_original_aspect_ratio=increase,"
            f"crop={VIDEO_WIDTH}:{VIDEO_HEIGHT},fps={FPS},setsar=1,"
            "eq=contrast=1.06:saturation=1.08"
        )
    else:
        input_args = ["-loop", "1", "-t", f"{duration:.4f}", "-i", str(media_path)]
        source_filter = (
            "scale=1240:2200:force_original_aspect_ratio=increase,"
            "crop=1080:1920:'(in_w-out_w)/2+14*sin(t*0.7)':'(in_h-out_h)/2+18*cos(t*0.5)',"
            f"fps={FPS},setsar=1,eq=contrast=1.06:saturation=1.08"
        )
    filter_complex = f"[0:v]{source_filter}[bg];[1:v]format=rgba[brand];[bg][brand]overlay=0:0:shortest=1,format=yuv420p[v]"
    run_ffmpeg([
        *input_args,
        "-loop", "1", "-t", f"{duration:.4f}", "-i", str(overlay_path),
        "-filter_complex", filter_complex,
        "-map", "[v]", "-an", "-r", str(FPS),
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "21",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(out_clip),
    ])


