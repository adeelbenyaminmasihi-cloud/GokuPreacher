def fetch_exact_scene_photo(query: str, filename: Path) -> Path:
    """Download a scene-specific photo, preferring Pexels; use generated art as fallback."""
    query = (query or "cinematic everyday life detail").strip()

    photo = _pexels_image(query, filename)
    if photo:
        return photo

    # Search-engine images are only a fallback; use assets you have rights to publish.
    try:
        encoded = urllib.parse.quote(f"{query} realistic photo portrait")
        url = (
            "https://www.bing.com/images/async?q=" + encoded
            + "&first=1&count=12&adlt=off&qft=+filterui:imagesize-large"
        )
        response = requests.get(url, headers=HEADERS, timeout=10)
        if response.status_code == 200:
            matches = re.findall(
                r'murl&quot;:&quot;(https?://[^&]+?\.(?:jpg|jpeg|png|webp)(?:\?[^&]*)?)&quot;',
                response.text,
                flags=re.I,
            )
            # Bing returns candidates in query relevance order; preserve that order.
            for image_url in matches[:8]:
                image_url = html.unescape(image_url)
                if image_url in USED_MEDIA_URLS:
                    continue
                if _download_file(image_url, filename, timeout=10) and verify_and_grade_image(filename):
                    USED_MEDIA_URLS.add(image_url)
                    return filename
    except requests.RequestException:
        pass

    # Image generation is a last resort; the result is checked before use.
    try:
        prompt = urllib.parse.quote(
            f"editorial photorealistic vertical 9:16 image of {query}, precise subject, realistic lighting, "
            "professional documentary photography, no text, no watermark"
        )
        url = f"https://image.pollinations.ai/prompt/{prompt}?width=1080&height=1920&nologo=true&seed={random.randint(1, 999999)}"
        if _download_file(url, filename, timeout=24) and verify_and_grade_image(filename):
            return filename
    except Exception:
        pass

    print(f"   ⚠️ No online image found for '{query}'; using a designed explainer graphic.")
    return create_fallback_graphic(query, filename)


def verify_and_grade_image(filepath: Path) -> bool:
    try:
        with Image.open(filepath) as original:
            im = ImageOps.exif_transpose(original).convert("RGB")
            width, height = im.size
            if width < 220 or height < 220:
                return False
            im = ImageEnhance.Contrast(im).enhance(1.06)
            im = ImageEnhance.Color(im).enhance(1.05)
            im.save(filepath, "JPEG", quality=92, optimize=True)
        return True
    except Exception:
        return False

