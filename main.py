def normalize_narration_text(text: str) -> str:
    """Make narration easier for Urdu voices and keep subtitles text-identical."""
    normalized = str(text or "").strip()
    for pattern, replacement in _PRONUNCIATION_REPLACEMENTS:
        normalized = re.sub(pattern, replacement, normalized, flags=re.IGNORECASE)
    normalized = re.sub(r"[ \t]+", " ", normalized)
    normalized = re.sub(r"\s+([،۔！？!?؛:])", r"\1", normalized)
    return normalized.strip()

def split_narration_sentences(text: str) -> List[str]:
    """Split at sentence boundaries so each spoken beat can have its own visual."""
    text = normalize_narration_text(text)
    parts = re.split(r"(?<=[۔.!?؟])\s+", text)
    clean = [part.strip() for part in parts if len(part.strip()) >= 8]
    return clean or ([text] if text else [])

def _query_tokens(text: str) -> set[str]:
    return {token.lower() for token in re.findall(r"[a-z0-9]+", str(text or "")) if len(token) > 2}

def _query_relevance_score(query: str, candidate_text: str) -> int:
    query_tokens = _query_tokens(query)
    candidate_tokens = _query_tokens(candidate_text)
    if not query_tokens or not candidate_tokens:
        return 0
    return len(query_tokens & candidate_tokens)

